#include <stdlib.h>
#include <stdio.h>
#include <fcntl.h>

/* macros */
#define PHYS_MEM_SIZE 256 * 256
#define NUM_FRAMES  256
#define PAGE_SIZE   256 /* 2^8 bytes */
#define FRAME_SIZE  256 /* 2^8 bytes */
#define PAGE_TABLE_SIZE 256
#define TLB_SIZE    16

/* globals */
int physical_memory[PHYS_MEM_SIZE];
FILE *backing_store;
unsigned int g_page_table[PAGE_TABLE_SIZE]; /* array used as page table -- each entry points a page # to frame # */
unsigned int tlb[TLB_SIZE][2]; /* matrix used as TLB -- each entry has a page # and frame # for lookup */

/* function prototypes */
void init_page_table(unsigned int* table);
void load_page_into_frame(int page, int offset);

int main(int argc, char** argv){
    backing_store = fopen("BACKING_STORE.bin", "r"); /* accessing simulated secondary storage */
    init_page_table(g_page_table);

    /* open addresses.txt for use */
    int filename = open("addresses.txt", O_RDONLY);
    if (filename < 0)
    {
        fprintf(stderr, "Error: addresses.txt could not be opened.");
        exit(1);
    }
    FILE *file = fdopen(filename, "r");
    char buffer[256];

    unsigned int addr;
    unsigned int page_num;
    unsigned int offset;
    
    /* page # and offset extraction */
    while ((fgets(buffer, sizeof(buffer), file)) != NULL)
    {
        addr = atoi(buffer);
        page_num = addr / PAGE_SIZE;
        offset = (addr & 0xFFFF) % PAGE_SIZE;

        if(g_page_table[page_num] == NULL){
            load_page_into_frame(page_num, offset);
        }

        //printf("addr: %u\n", addr);
        //printf("page: %u\n", page);
        //printf("offset: %u\n", offset);
    }

    return 0;
}

/* initializes all entries in page table to -1 to mark as invalid for page faults */
void init_page_table(unsigned int* table){
    for(int i = 0; i < PAGE_TABLE_SIZE; ++i){
        table[i] = -1;
    }
    return;
}

/* generated by AI to assist with loading to physical memory */
/* loads a virtual page onto a physical frame when */
void load_page_into_frame(int page_num, int frame_num){
    /* we set the pointer to the start of the page we're looking for in storage*/
    fseek(backing_store, page_num * PAGE_SIZE, SEEK_SET);

    /* read page-sized-chunk of bytes into physical memory at the allocated frame */
    fread(&physical_memory[frame_num * FRAME_SIZE], sizeof(unsigned int), PAGE_SIZE, backing_store);
}